type PixelTextProps = {
  value: string;
  /** Characters from this index on are drawn in terracotta. */
  accentFrom?: number;
  className?: string;
};

// Text drawn in brand squares. Decorative — pair it with readable text.
export function PixelText({ value, accentFrom = Infinity, className = "" }: PixelTextProps) {
  const chars = [...value.toUpperCase()].filter((char) => glyphs[char]);
  const width = chars.length * 6 - 1;

  return (
    <svg viewBox={`0 0 ${width} 7`} aria-hidden="true" className={className}>
      {chars.flatMap((char, index) =>
        glyphs[char].flatMap((row, y) =>
          [...row].map((cell, x) =>
            cell === "#" ? (
              <rect
                key={`${index}-${x}-${y}`}
                x={index * 6 + x + 0.06}
                y={y + 0.06}
                width="0.88"
                height="0.88"
                fill={index >= accentFrom ? "var(--primary)" : "currentColor"}
              />
            ) : null,
          ),
        ),
      )}
    </svg>
  );
}
